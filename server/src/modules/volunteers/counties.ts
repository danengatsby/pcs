export type CountyName = (typeof countyNames)[number];

export function normalizeCountyKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/[^a-z0-9]+/g, "");
}

const countyByNormalizedKey = new Map<string, CountyName>(
  countyNames.map((name) => [normalizeCountyKey(name), name] as const)
);

export function resolveCountyName(value: string): CountyName | null {
  const key = normalizeCountyKey(value);
  if (!key) {
    return null;
  }

  return countyByNormalizedKey.get(key) ?? null;
}
